const fs = require('node:fs');
const path = require('node:path');
const { test, expect } = require('@playwright/test');

const accounts = JSON.parse(fs.readFileSync(process.env.FE14_ACCOUNT_FILE || '/run/fe14/accounts.json', 'utf8'));
const artifacts = process.env.FE14_ARTIFACT_DIR || '/run/fe14/artifacts';
const head = process.env.FE14_HEAD || 'unknown';

test('GADM-03 reports and scoped audit work through Angular, Go, and disposable PostGIS', async ({ page }) => {
  const api = process.env.FE14_API_BASE_URL || 'http://backend:8080/api/v1';
  const login = await page.request.post(`${api}/auth/login`, { data: { email: accounts.admin.email, password: accounts.admin.password } });
  expect(login.status()).toBe(200);
  const token = (await login.json()).access_token;
  const headers = { Authorization: `Bearer ${token}` };
  const now = new Date();
  const until = now.toISOString();
  const from = new Date(now.getTime() - 30 * 86400000).toISOString();
  const params = new URLSearchParams({ from, until, time_zone: 'America/Santiago' });
  const kpis = await page.request.get(`${api}/admin/global/kpis?${params}`, { headers });
  expect(kpis.status()).toBe(200);
  const report = (await kpis.json()).data;
  expect(report.generated_at).toBeTruthy();
  expect(report.account_roles).toBeTruthy();
  for (const movement of report.finance) expect(typeof movement.amount_clp).toBe('string');
  const nonGlobalLogin = await page.request.post(`${api}/auth/login`, { data: { email: accounts.thirdParty.email, password: accounts.thirdParty.password } });
  expect(nonGlobalLogin.status()).toBe(200);
  const nonGlobalHeaders = { Authorization: `Bearer ${(await nonGlobalLogin.json()).access_token}` };
  expect((await page.request.get(`${api}/admin/global/kpis?${params}`, { headers: nonGlobalHeaders })).status()).toBe(403);
  expect((await page.request.get(`${api}/admin/global/audit-events?${params}`, { headers: nonGlobalHeaders })).status()).toBe(403);
  expect((await page.request.get(`${api}/admin/global/audit-events/export?${new URLSearchParams({ ...Object.fromEntries(params), format: 'csv' })}`, { headers: nonGlobalHeaders })).status()).toBe(403);

  const accountsPage = await page.request.get(`${api}/admin/global/accounts?email_prefix=${encodeURIComponent(accounts.renter.email)}&page_size=1`, { headers });
  expect(accountsPage.status()).toBe(200);
  const targetId = (await accountsPage.json()).data.items[0]?.account_id;
  expect(targetId).toBeTruthy();
  const targetRead = await page.request.get(`${api}/admin/global/accounts/${targetId}`, { headers });
  expect(targetRead.status()).toBe(200);
  const actorId = (await page.request.get(`${api}/admin/global/me`, { headers }).then(r => r.json())).data.account_id;
  const auditParams = new URLSearchParams({ from, until: new Date().toISOString(), actor_id: actorId, target_account_id: targetId, page_size: '25' });
  const audit = await page.request.get(`${api}/admin/global/audit-events?${auditParams}`, { headers });
  expect(audit.status()).toBe(200);
  const events = (await audit.json()).data;
  expect(events.applied_filters.actor_id).toBe(auditParams.get('actor_id'));
  expect(events.applied_filters.target_account_id).toBe(targetId);
  expect(events.items.some((event) => event.target_account_id === targetId && event.actor_id === auditParams.get('actor_id'))).toBeTruthy();
  const csv = await page.request.get(`${api}/admin/global/audit-events/export?${new URLSearchParams({ ...Object.fromEntries(auditParams), format: 'csv' })}`, { headers });
  expect(csv.status()).toBe(200);
  expect(csv.headers()['content-type']).toContain('text/csv');
  expect(await csv.text()).toContain('target_account_id');

  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/acceso');
  await page.getByLabel('Correo electrónico').fill(accounts.admin.email);
  await page.getByLabel('Contraseña').fill(accounts.admin.password);
  await page.getByRole('button', { name: 'Iniciar sesión' }).click();
  await expect(page).toHaveURL(/\/mi-cuenta$/);
  await page.getByRole('button', { name: 'Abrir menú' }).click();
  await page.getByRole('link', { name: 'Administración global' }).click();
  await page.getByRole('button', { name: 'Indicadores y auditoría' }).click();
  await expect(page.getByRole('heading', { name: 'Indicadores persistidos' })).toBeVisible();
  await expect(page.getByText('Cuentas activas no representa DAU.', { exact: false })).toBeVisible();
  const localInput = (instant) => new Date(instant.getTime() - instant.getTimezoneOffset() * 60000).toISOString().slice(0, 16);
  await page.getByLabel('Desde', { exact: true }).last().fill(localInput(new Date(Date.now() - 30 * 86400000)));
  await page.getByLabel('Hasta (exclusivo)', { exact: true }).last().fill(localInput(new Date(Date.now() + 60000)));
  await page.getByLabel('Actor UUID').fill(actorId);
  await page.getByLabel('Cuenta objetivo UUID').fill(targetId);
  const uiAuditResponsePromise = page.waitForResponse((response) => response.url().includes('/admin/global/audit-events?') && response.request().method() === 'GET');
  await page.getByRole('button', { name: 'Aplicar filtros' }).click();
  const uiAuditResponse = await uiAuditResponsePromise;
  expect(uiAuditResponse.status()).toBe(200);
  const uiAuditBody = (await uiAuditResponse.json()).data;
  expect(uiAuditBody.items.some((event) => event.target_account_id === targetId && event.actor_id === actorId), JSON.stringify({ filters: uiAuditBody.applied_filters, events: uiAuditBody.items.map((event) => ({ action: event.action, actor_id: event.actor_id, target_account_id: event.target_account_id, occurred_at: event.occurred_at })) })).toBeTruthy();
  await expect(page.getByRole('table').getByText(targetId, { exact: false }).first()).toBeVisible();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exportar CSV' }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toContain('.csv');
  await page.screenshot({ path: path.join(artifacts, 'fe14_gadm_03_admin_mobile.jpg'), type: 'jpeg', quality: 86, fullPage: true });
  const mobile = await page.evaluate((commit) => ({ viewport: { width: innerWidth, height: innerHeight }, document: { width: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight }, head: commit }), head);
  expect(mobile.document.width).toBeLessThanOrEqual(390);
  fs.writeFileSync(path.join(artifacts, 'fe14_gadm_03_admin_mobile.json'), JSON.stringify(mobile, null, 2));
  await page.setViewportSize({ width: 1365, height: 900 });
  const desktop = await page.evaluate((commit) => ({ viewport: { width: innerWidth, height: innerHeight }, document: { width: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight }, head: commit }), head);
  expect(desktop.document.width).toBeLessThanOrEqual(1365);
  await page.screenshot({ path: path.join(artifacts, 'fe14_gadm_03_admin_desktop.jpg'), type: 'jpeg', quality: 86, fullPage: true });
  fs.writeFileSync(path.join(artifacts, 'fe14_gadm_03_admin_desktop.json'), JSON.stringify(desktop, null, 2));
});
