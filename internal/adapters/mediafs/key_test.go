package mediafs

import "testing"

func TestValidateV1AndV2MediaKeys(t *testing.T) {
	valid := []string{"media/v1/spaces/00000000-0000-4000-8000-000000000001/00000000-0000-4000-8000-000000000002/1/display.webp", "media/v1/profiles/00000000-0000-4000-8000-000000000001/00000000-0000-4000-8000-000000000002/2/avatar.webp", "users/00000000-0000-4000-8000-000000000010/spaces/00000000-0000-4000-8000-000000000001/images/v2/00000000-0000-4000-8000-000000000002/20261027T153456.123456789Z_42_display.webp"}
	for _, k := range valid {
		if validateKey(k) != nil {
			t.Errorf("rejected %q", k)
		}
	}
	invalid := []string{"media/v1/../secret", "media/v2/spaces/x", "users/00000000-0000-4000-8000-000000000010/spaces/00000000-0000-4000-8000-000000000001/images/v2/00000000-0000-4000-8000-000000000002/20261027T153456.123456789Z_0_display.webp", "users/00000000-0000-4000-8000-000000000010/spaces/00000000-0000-4000-8000-000000000001/images/v2/00000000-0000-4000-8000-000000000002/20261027T153456.123456789Z_42_original.jpg", "users/00000000-0000-4000-8000-000000000010/spaces/00000000-0000-4000-8000-000000000001/images/v2/00000000-0000-4000-8000-000000000002/abcdefghT153456.123456789Z_42_display.webp", "users/00000000-0000-4000-8000-000000000010/spaces/00000000-0000-4000-8000-000000000001/images/v2/00000000-0000-4000-8000-000000000002/20260230T153456.123456789Z_42_display.webp", "users/00000000-0000-4000-8000-000000000010/spaces/00000000-0000-4000-8000-000000000001/images/v2/00000000-0000-4000-8000-00000000000g/20261027T153456.123456789Z_42_display.webp"}
	for _, k := range invalid {
		if validateKey(k) == nil {
			t.Errorf("accepted %q", k)
		}
	}
}
